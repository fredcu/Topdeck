import Foundation

/// What the clipboard history never keeps: copies the copying app marks secret or temporary, copies
/// made in a password manager, and copies from apps the user chose to skip. No AppKit, so it tests
/// anywhere.
struct ClipboardRules: Equatable, Sendable {
    /// Types an app adds to say a copy is secret, temporary, or made by a program (nspasteboard.org).
    static let markedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
    ]
    /// Types that password managers and text expanders put on their copies.
    static let passwordManagerTypes: Set<String> = [
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping",
        "net.antelle.keeweb", "Pasteboard generator type",
    ]
    /// Password managers, whose copies are never kept even when they don't mark them. The user's list
    /// can't take them off.
    static let passwordManagers: Set<String> = [
        "com.1password.1password", "com.agilebits.onepassword7", "com.agilebits.onepassword-osx",
        "com.bitwarden.desktop", "com.dashlane.dashlanephonefinal", "org.keepassxc.keepassxc",
        "com.lastpass.LastPass", "com.apple.keychainaccess", "com.apple.Passwords", "in.sinew.Enpass-Desktop",
        "me.proton.pass.electron", "net.antelle.keeweb", "com.markmcguill.strongbox.mac",
    ]
    /// The type a copying app names itself with (nspasteboard.org): its bundle ID, which is more exact
    /// than the app in front when a password manager copies from a menu or a browser extension.
    static let sourceType = "org.nspasteboard.source"

    private static let managerIDs = Set(passwordManagers.map { $0.lowercased() })

    /// Bundle IDs of the apps the user chose to skip.
    var ignoredApps: Set<String> = []

    /// Whether a copy carrying `types`, made in any of `apps` (the app in front, and the one the copy
    /// names as its source, whichever are known), stays out of the history.
    func ignores(types: some Sequence<String>, apps: [String?]) -> Bool {
        let types = Set(types)
        guard types.isDisjoint(with: Self.markedTypes), types.isDisjoint(with: Self.passwordManagerTypes) else {
            return true
        }
        // Bundle IDs aren't case-sensitive.
        let skipped = Self.managerIDs.union(ignoredApps.map { $0.lowercased() })
        return apps.contains { app in app.map { skipped.contains($0.lowercased()) } ?? false }
    }
}
